// --- PAGE INITIALIZATION ---
document.addEventListener('DOMContentLoaded', () => {
    // 1. Populate States in Registration Form
    const stateSelect = document.getElementById('reg-state');
    const lgaSelect = document.getElementById('reg-lga');

    if (stateSelect && lgaSelect) {
        // Sort states alphabetically and populate
        Object.keys(nigeriaData).sort().forEach(state => {
            const option = document.createElement('option');
            option.value = state;
            option.innerText = state;
            stateSelect.appendChild(option);
        });

        // Event: When State Changes -> Populate LGAs
        stateSelect.addEventListener('change', function() {
            const selectedState = this.value;
            lgaSelect.innerHTML = '<option value="">Select LGA</option>'; // Clear old options

            if (selectedState && nigeriaData[selectedState]) {
                lgaSelect.disabled = false;
                lgaSelect.classList.remove('bg-gray-100');
                lgaSelect.classList.add('bg-white');
                
                nigeriaData[selectedState].sort().forEach(lga => {
                    const option = document.createElement('option');
                    option.value = lga;
                    option.innerText = lga;
                    lgaSelect.appendChild(option);
                });
            } else {
                lgaSelect.disabled = true;
                lgaSelect.classList.add('bg-gray-100');
            }
        });
    }

    // 2. Check Login Status
    checkLoginStatus();
});

// --- STATE MANAGEMENT ---
let generatedOTP = null;
let tempUserData = null;

// --- REGISTRATION LOGIC ---
const regForm = document.getElementById('registerForm');
if (regForm) {
    regForm.addEventListener('submit', (e) => {
        e.preventDefault();
        
        // 1. Collect Data
        const name = document.getElementById('reg-name').value;
        const email = document.getElementById('reg-email').value;
        const address = document.getElementById('reg-address').value;
        const house = document.getElementById('reg-house').value;
        const state = document.getElementById('reg-state').value;
        const lga = document.getElementById('reg-lga').value;
        const pass = document.getElementById('reg-pass').value;

        // 2. Validate User Existence
        const usersDB = JSON.parse(localStorage.getItem('kcr_users_db')) || [];
        if (usersDB.find(u => u.email === email)) {
            document.getElementById('reg-error').classList.remove('hidden');
            return;
        }

        // 3. Generate OTP & Store Temp Data
        generatedOTP = Math.floor(1000 + Math.random() * 9000); // Random 4 digits
        tempUserData = { name, email, address, house, state, lga, pass };

        // 4. Simulate Sending Email (Show Alert)
        alert(`📧 EMAIL SIMULATION:\n\nVerification Code Sent to ${email}.\n\nYour Code is: ${generatedOTP}`);

        // 5. Show Modal
        document.getElementById('otp-modal').classList.remove('hidden');
    });
}

// --- OTP VERIFICATION ---
function verifyOTP() {
    const inputCode = document.getElementById('otp-input').value;

    if (parseInt(inputCode) === generatedOTP) {
        // Success! Save User to DB
        const usersDB = JSON.parse(localStorage.getItem('kcr_users_db')) || [];
        usersDB.push(tempUserData);
        localStorage.setItem('kcr_users_db', JSON.stringify(usersDB));

        alert("✅ Account Verified! Redirecting to Login...");
        window.location.href = 'login.html';
    } else {
        alert("❌ Invalid Code. Please try again.");
    }
}

function closeOtpModal() {
    document.getElementById('otp-modal').classList.add('hidden');
}


// --- LOGIN LOGIC ---
const loginForm = document.getElementById('loginForm');
if (loginForm) {
    loginForm.addEventListener('submit', (e) => {
        e.preventDefault();
        
        const email = document.getElementById('login-id').value;
        const pass = document.getElementById('login-password').value;
        const errorMsg = document.getElementById('login-error-msg');

        const usersDB = JSON.parse(localStorage.getItem('kcr_users_db')) || [];
        const foundUser = usersDB.find(u => u.email === email && u.pass === pass);

        if (foundUser) {
            localStorage.setItem('kcr_current_user', JSON.stringify(foundUser));
            window.location.href = 'dashboard.html';
        } else {
            errorMsg.innerText = "❌ Incorrect Email or Password";
            errorMsg.classList.remove('hidden');
        }
    });
}


// --- LOGOUT & AUTH CHECKS ---
function appLogOut() {
    localStorage.removeItem('kcr_current_user');
    window.location.href = 'login.html';
}

function checkLoginStatus() {
    const currentUser = JSON.parse(localStorage.getItem('kcr_current_user'));
    const path = window.location.pathname;

    // Protection
    if (path.includes('dashboard.html') && !currentUser) {
        window.location.href = 'login.html';
    }
    if ((path.includes('login.html') || path.includes('register.html')) && currentUser) {
        window.location.href = 'dashboard.html';
    }

    // Display Name
    if (path.includes('dashboard.html') && currentUser) {
        const display = document.getElementById('user-display');
        if(display) display.innerText = `👤 ${currentUser.name} (${currentUser.state})`;
    }
}